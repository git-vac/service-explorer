import html
import json
import os
from pathlib import Path
import unicodedata

from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.text import Text
from rich.tree import Tree


def clean(value):
    return "".join(c for c in str(value) if c in "\n\t" or not unicodedata.category(c).startswith("C"))


def new_file(path, data, binary=False):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "wb" if binary else "w", **({} if binary else {"encoding": "utf-8", "newline": "\n"})) as stream:
        stream.write(data)


def terminal(report, console=None):
    console = console or Console(highlight=False)
    console.print(Panel(Text(report["title"]), border_style="cyan"))
    for warning in report.get("warnings", []):
        console.print(Panel(Text(clean(warning)), border_style="yellow", title="Review"))
    if "accounts" in report:
        root = Tree(Text("Mailbox export"))
        for account in report["accounts"]:
            branch = root.add(Text(f'{account["username"]} @ {account["host"]} [{account["protocol"].upper()}]'))
            if account.get("error"):
                branch.add(Text(account["error"], style="red"))
            for box in account.get("mailboxes", []):
                node = branch.add(Text(f'{box["name"]} — {box["total"]} remote / {len(box["messages"])} saved'))
                for warning in box.get("warnings", []):
                    node.add(Text(clean(warning), style="yellow"))
                for msg in box["messages"]:
                    node.add(Text(f'{msg["id"]}  {msg["subject"]}  ({msg["from"]})'))
        console.print(root)
    elif "queries" in report:
        console.print(Text(f'Server: {report["server"]}:{report["port"]} · Recursion requested: {report["recursive"]}'))
        for query in report["queries"]:
            console.print(Text(f'\n{query["name"]} · {query["type"]} · {query["status"]} · {query.get("transport", "-")}', style="bold"))
            console.print(Text("Flags: " + query.get("flags", "-") + " · " + query.get("detail", ""), style="dim"))
            table = Table(expand=True)
            for label in ("Section", "Name", "TTL", "Type", "Value"):
                table.add_column(label, overflow="fold")
            for rr in query.get("records", []):
                table.add_row(*(Text(clean(rr[k])) for k in ("section", "name", "ttl", "type", "value")))
            console.print(table)
        if report.get("zone_transfer"):
            zone = report["zone_transfer"]
            console.print(Panel(Text(json.dumps(zone, ensure_ascii=False, indent=2)), title="Requested zone transfer"))
    else:
        console.print(Text(f'{report["protocol"].upper()} · {report["host"]} · {report["security"]}', style="bold"))
        console.print(Panel(Text(report.get("greeting", "Unreported")), title="Server greeting"))
        table = Table(expand=True)
        table.add_column("Connection stage")
        table.add_column("Advertised capabilities", overflow="fold")
        for key, label in (("initial_capabilities", "Initial"), ("current_capabilities", "Current")):
            value = report.get(key, [])
            content = "\n".join(f'{k}: {", ".join(v) if isinstance(v, list) else v}' for k, v in value.items()) if isinstance(value, dict) else "\n".join(value)
            table.add_row(Text(label), Text(content))
        console.print(table)
        certificate = report.get("certificate")
        if certificate:
            for key in ("subject", "issuer", "notBefore", "notAfter", "subjectAltName"):
                if key in certificate:
                    console.print(Text(key + ": " + clean(certificate[key])))
        else:
            console.print(Text("Certificate metadata not available.", style="dim"))


def webpage(report):
    e = lambda v: html.escape(clean(v), quote=True)
    sections = []
    for account in report.get("accounts", []):
        sections.append(f'<h2>{e(account["username"])} @ {e(account["host"])}</h2>')
        if account.get("error"):
            sections.append(f'<p class="warning">{e(account["error"])}</p>')
        for box in account.get("mailboxes", []):
            rows = []
            for msg in box["messages"]:
                # Paths are generated by us and restricted to portable filename characters.
                rows.append(f'<tr><td>{e(msg["date"])}</td><td>{e(msg["from"])}</td>'
                    f'<td><a href="{e(msg["text_path"])}">{e(msg["subject"])}</a></td><td><a href="{e(msg["raw_path"])}">Original email</a></td></tr>')
            sections.append(f'<article><h3>{e(box["name"])} <small>{box["total"]} remote / {len(box["messages"])} saved</small></h3>'
                + "".join(f'<p class="warning">{e(w)}</p>' for w in box.get("warnings", []))
                + '<div class="scroll"><table><thead><tr><th>Date</th><th>From</th><th>Subject</th><th>Source</th></tr></thead><tbody>'
                + "".join(rows) + '</tbody></table></div></article>')
    for query in report.get("queries", []):
        rows = "".join('<tr>' + "".join(f'<td>{e(rr[k])}</td>' for k in ("section", "name", "ttl", "type", "value")) + '</tr>'
            for rr in query.get("records", []))
        sections.append(f'<article><h2>{e(query["name"])} · {e(query["type"])}</h2><p>{e(query["status"])} · {e(query.get("transport", ""))} · {e(query.get("flags", ""))}</p>'
            f'<p>{e(query.get("detail", ""))}</p><div class="scroll"><table><thead><tr><th>Section</th><th>Name</th><th>TTL</th><th>Type</th><th>Value</th></tr></thead><tbody>{rows}</tbody></table></div></article>')
    if not sections:
        sections.append('<pre>' + e(json.dumps(report, ensure_ascii=False, indent=2)) + '</pre>')
    else:
        sections.append('<details><summary>Full collected metadata</summary><pre>' + e(json.dumps(report, ensure_ascii=False, indent=2)) + '</pre></details>')
    return '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' \
        '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; style-src \'unsafe-inline\'; base-uri \'none\'">' \
        '<title>' + e(report["title"]) + '</title><style>' \
        'body{background:#0b1220;color:#e5edf8;font:16px/1.6 system-ui;margin:0}main{max-width:1150px;margin:auto;padding:36px 24px}h1{font-size:34px}h2{font-size:22px}h3{font-size:18px}small,p{color:#a8b8cc}article,details{background:#142036;border:1px solid #2b3a53;border-radius:12px;padding:20px;margin:18px 0}table{width:100%;border-collapse:collapse}th,td{text-align:left;padding:12px;border-bottom:1px solid #2b3a53}a{color:#7dd3fc}.warning{color:#fbbf24}.scroll{overflow:auto}pre{white-space:pre-wrap;overflow-wrap:anywhere}summary{cursor:pointer;color:#67e8c1}' \
        '</style></head><body><main><p>SERVICE EXPLORER · LOCAL LAB REVIEW</p><h1>' + e(report["title"]) + '</h1>' \
        + "".join(f'<p class="warning">{e(w)}</p>' for w in report.get("warnings", [])) + "".join(sections) \
        + '</main></body></html>'
